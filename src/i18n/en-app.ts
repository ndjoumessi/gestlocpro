/**
 * LA SECTION `app` DU DICTIONNAIRE ANGLAIS — scindée pour la même raison que sa
 * jumelle française, mais pas par le même chemin.
 *
 * ═══ CE QUI EST MESURÉ ═══
 *
 * `en.ts` n'a JAMAIS été impatient : `I18nProvider` le charge par `import('./en')`,
 * donc un visiteur français ne le télécharge pas du tout. Le défaut était plus
 * étroit : un visiteur ANGLAIS de la vitrine téléchargeait les mots des écrans
 * de gestion avec ceux de la page de vente. Le paquet `en` pesait 36 609 o
 * compressés, dont 67 % pour cette section — ~24 Ko de mots qu'il ne verrait
 * jamais, soit ~480 ms sur le réseau de référence du dépôt.
 *
 * ═══ POURQUOI PAS LE MÊME CHEMIN QUE `fr-app.ts` ═══
 *
 * Le français évite une requête supplémentaire parce que `EspaceApplicatif.tsx`
 * importe `fr-app` STATIQUEMENT : le français est la langue par défaut, ses mots
 * voyagent dans un morceau que l'écran télécharge de toute façon.
 *
 * CETTE ISSUE N'EXISTE PAS ICI. Un import statique de ce fichier depuis
 * `EspaceApplicatif.tsx` mettrait les mots ANGLAIS dans le morceau applicatif
 * que les utilisateurs FRANÇAIS téléchargent — l'exact inverse du but. La
 * moitié anglaise doit donc arriver par son propre `import()`.
 *
 * ═══ ET LA REQUÊTE AJOUTÉE NE COÛTE PAS DE TEMPS, C'EST MESURÉ ═══
 *
 * Ce dépôt refuse les requêtes ajoutées — « les octets se rapportent ; les
 * requêtes se refusent », quatre refus à son actif. Cette règle visait des
 * requêtes SÉRIALISÉES sur le chemin critique. Celle-ci ne l'est pas :
 *
 *     EspaceApplicatif  153 895 o gzip
 *     en-app             ~24 000 o gzip   — 6,4 fois plus petit
 *
 * Les deux partent dans le MÊME battement depuis `chargerEspaceApplicatif`
 * (`App.tsx`), derrière l'attente qui existait déjà. La moitié anglaise arrive
 * donc largement avant son aîné, et le temps au mur ne bouge pas.
 *
 * C'EST AUSSI CE QUI INTERDIT L'ÉCRAN BLANC. `t()` rend `''` pour une clé
 * absente — c'est un choix assumé du fournisseur, pas un défaut. Si la moitié
 * applicative arrivait APRÈS le premier rendu d'un écran, l'utilisateur anglais
 * verrait un tableau de bord vide de tout texte. En joignant les deux promesses
 * à la MÊME frontière `Suspense`, React garantit qu'aucun écran ne se rend avant
 * ses mots : ce n'est pas une convention qu'on se rappellerait de tenir.
 */
